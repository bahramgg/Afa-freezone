/**
 * What the guides say.
 *
 * The audience is the free zone's own officials, not engineers. Every sentence
 * here has to survive being read once, on a screen, by somebody who has never
 * opened the system — so nothing is explained by naming a technology, and
 * nothing is left out because it is obvious to whoever built it.
 *
 * Two things are produced from this file: a narrated-by-caption video per panel
 * and a written document per panel. They say the same thing at different
 * lengths, deliberately, so that watching one and reading the other does not
 * produce two different accounts of the same system.
 */

export type PanelKey = "user" | "foreign" | "admin" | "bank";

/** One node on the flow diagram — a place the trade actually stops. */
export type Node = {
  label: string;
  /** Who is acting here. Colours the node and names the responsible party. */
  actor: "merchant" | "foreign" | "admin" | "bank" | "chain";
};

export type Flow = {
  title: string;
  subtitle: string;
  nodes: Node[];
};

