/**
 * How long a beat stays on screen.
 *
 * There is no narration, so the viewer reads every word — which makes the
 * duration a function of how much there is to read, not a number somebody
 * guessed while writing. Around two words a second is an unhurried pace for
 * Persian on a screen, and a diagram needs a few seconds of its own before the
 * text underneath it means anything.
 *
 * The hand-written `seconds` acts as a floor, so a short beat that still needs
 * to land — a section title, a cover — is not rushed off.
 */
export function beatSeconds(beat: Beat): number {
  const words = (text?: string) => (text ? text.trim().split(/\s+/).length : 0);
  const read =
    words(beat.heading) / 2.4 +
    words(beat.body) / 2.7 +
    (beat.bullets ?? []).reduce((n, b) => n + words(b) / 2.7 + 0.6, 0);

  const wanted = 3 + read + (beat.flow ? 3 : 0);
  // Past about twenty seconds a still screen stops being read and starts being
  // stared at. A beat that wants longer than this is too dense, not too fast.
  return Math.round(Math.min(22, Math.max(beat.seconds, wanted)));
}

/** How long a panel's video runs, in seconds. */
export const runtimeOf = (panel: Panel) =>
  panel.beats.reduce((total, beat) => total + beatSeconds(beat), 0);
