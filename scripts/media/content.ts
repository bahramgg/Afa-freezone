/** One held moment in a video: what is on screen and for how long. */
export type Beat = {
  kind: "cover" | "section" | "step" | "point" | "close";
  heading: string;
  body?: string;
  bullets?: string[];
  flow?: Flow;
  /** Which node of the flow is being described. Earlier nodes read as done. */
  active?: number;
  seconds: number;
};

export type Panel = {
  key: PanelKey;
  title: string;
  audience: string;
  /** The one-line answer to "what is this panel for". */
  purpose: string;
  accent: string;
  beats: Beat[];
  document: DocSection[];
};

/** One part of the written guide. */
export type DocSection = {
  heading: string;
  paragraphs?: string[];
  /** A numbered walk-through of the flow. */
  steps?: { title: string; text: string }[];
  bullets?: string[];
  flow?: Flow;
  /** Starts a new page before this section. */
  breakBefore?: boolean;
};

